public class Main {
    public static void main(String[] args) {

        // Создаём массив целых чисел из трёх элементов
        // Индексы в массиве: 0, 1, 2
        int[] numbers = {1, 2, 3};

        // Блок try — сюда помещаем код, который может вызвать ошибку
        try {
            // Пытаемся вывести элемент с индексом 5
            // Но такого индекса нет, поэтому возникнет исключение
            System.out.println(numbers[5]);

            // Блок catch — ловим конкретное исключение ArrayIndexOutOfBoundsException
            // Переменная e хранит информацию об ошибке (мы её не используем, но она обязательна)
        } catch (ArrayIndexOutOfBoundsException e) {

            // Выводим своё понятное сообщение, если ошибка произошла
            System.out.println("Ошибка: выход за границы массива");

        }
    }
}